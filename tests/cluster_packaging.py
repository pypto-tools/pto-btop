"""Verify real release installation, upgrades, preserved data and failed updates."""
import hashlib
import json
import os
import runpy
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile


source, build, cmake = sys.argv[1:4]
package_options = sys.argv[4:]


def run(*command, succeeds=True):
    result = subprocess.run(command, capture_output=True, text=True, timeout=40)
    assert (result.returncode == 0) == succeeds, (command, result.returncode, result.stdout, result.stderr)
    return result.stdout + result.stderr


def check_enrollment_bootstrap(base, archive, metadata):
    """Exercise the released installer while replacing only the network commands."""
    assets = base / "bootstrap-assets"
    assets.mkdir()
    for arch in ("amd64", "arm64"):
        target = assets / f"pto-btop-{metadata['version']}-linux-{arch}.tar.gz"
        shutil.copy2(archive, target)
        digest = hashlib.sha256(target.read_bytes()).hexdigest()
        target.with_name(target.name + ".sha256").write_text(f"{digest}  {target.name}\n")
    run(sys.executable, str(Path(source) / "scripts/package-bootstrap.py"), "--assets", str(assets))
    bundle = base / "enrollment"
    node = bundle / "node"
    node.mkdir(parents=True)
    shutil.copy2(assets / "setup.py", bundle / "setup.py")
    bootstrap = runpy.run_path(str(bundle / "setup.py"), run_name="bootstrap_test")
    command = [sys.executable, "-c", "import time; time.sleep(30)"]
    process = subprocess.Popen(command)
    try:
        try:
            bootstrap["stop_background_agent"](process.pid, [sys.executable, "wrong-command"])
        except ValueError as error:
            assert "refusing to stop" in str(error)
        else:
            raise AssertionError("Installer tried to stop an unrelated process")
        assert process.poll() is None
        bootstrap["stop_background_agent"](process.pid, command)
        process.wait(timeout=3)
    finally:
        if process.poll() is None:
            process.terminate()
            process.wait(timeout=3)
    (bundle / "node.json").write_text(json.dumps({"id": "dev-a", "netbird_ip": "192.0.2.1",
        "hub": "https://192.0.2.2:8443", "version": "0.4.0-alpha.1", "package_sha256": {}}))
    for name in ("agent.json", "client.json", "agent.token", "viewer.token", "ca.pem"):
        (node / name).write_text("private test enrollment\n")
    fakebin = base / "fakebin"
    fakebin.mkdir()
    (fakebin / "ip").write_text(f"#!{sys.executable}\nprint('[{{\"addr_info\":[{{\"family\":\"inet\",\"local\":\"192.0.2.1\"}}]}}]')\n")
    (fakebin / "curl").write_text(f"#!{sys.executable}\nimport pathlib, shutil, sys\n"
        f"assets=pathlib.Path({str(assets)!r})\n"
        "url=sys.argv[sys.argv.index('--url')+1]\n"
        "target=sys.argv[sys.argv.index('--output')+1]\n"
        "shutil.copy2(assets / url.rsplit('/',1)[1],target)\n")
    for executable in fakebin.iterdir():
        executable.chmod(0o700)
    previous_path = os.environ["PATH"]
    os.environ["PATH"] = str(fakebin) + os.pathsep + previous_path
    try:
        root, bindir = base / "enrolled", base / "enrolled-bin"
        command = (sys.executable, str(bundle / "setup.py"), "--root", str(root),
                   "--bin-dir", str(bindir), "--proxy", "http://127.0.0.1:7892")
        output = run(*command, "--check")
        assert "no installation" in output and not root.exists()
        assert "cannot be combined" in run(*command, "--check", "--restart-agent", succeeds=False)
        run(*command, "--install-only")
        run(*command, "--install-only")
        for original in node.iterdir():
            installed = root / "config/node" / original.name
            assert installed.read_bytes() == original.read_bytes()
            assert installed.stat().st_mode & 0o777 == 0o600
        target = assets / archive.name
        payload = target.read_bytes()
        target.write_bytes(b"corrupt download")
        assert "checksum mismatch" in run(*command, "--check", succeeds=False)
        target.write_bytes(payload)
        (node / "agent.token").write_text("conflicting enrollment")
        assert "refusing to replace" in run(*command, "--install-only", succeeds=False)
    finally:
        os.environ["PATH"] = previous_path


with tempfile.TemporaryDirectory(prefix="pto-btop-install-test-") as directory:
    base = Path(directory)
    run(sys.executable, str(Path(source) / "scripts/package.py"), "--build-dir", build,
        "--cmake", cmake, "--output-dir", str(base / "dist"), *package_options)
    archive, = (base / "dist").glob("*.tar.gz")
    expected = archive.with_name(archive.name + ".sha256").read_text().split()[0]
    assert hashlib.sha256(archive.read_bytes()).hexdigest() == expected
    with tarfile.open(archive) as packaged:
        # The archive was just generated by this test from the local build.
        packaged.extractall(base / "unpacked")
    package, = (base / "unpacked").iterdir()
    metadata = json.loads((package / "package.json").read_text())
    if metadata["openssl_linkage"] == "static":
        assert not any(name.startswith(("libssl.so", "libcrypto.so")) for name in metadata["libraries"])
        assert (package / "share/btop-cluster/licenses/OpenSSL-LICENSE").is_file()
    check_enrollment_bootstrap(base, archive, metadata)
    # A stricter compatibility cap must reject this build without producing an archive.
    run(sys.executable, str(Path(source) / "scripts/package.py"), "--build-dir", build,
        "--cmake", cmake, "--output-dir", str(base / "rejected"), *package_options,
        "--max-glibc", "2.0", succeeds=False)
    assert not list((base / "rejected").glob("*.tar.gz"))
    installer = package / "install.py"
    root, bindir = base / "installed", base / "commands"
    command = (sys.executable, str(installer), "--root", str(root), "--bin-dir", str(bindir))
    run(*command, "--check")
    assert not root.exists() and not bindir.exists()
    run(*command)
    initial = (root / "app/current").readlink()
    for name in ("config", "state", "logs", "tmp"):
        marker = root / name / "preserve-me"
        marker.write_bytes(b"user data\x00\xff")
        marker.chmod(0o600)
    run(*command)
    assert (root / "app/current").readlink() == initial
    assert "localhost" in run(str(bindir / "pto-btop"), "--local", "--check")
    for name in ("pto-btop", "pto-btop-agent", "pto-btop-server"):
        assert name in run(str(bindir / name), "--version")
    unit = (root / "app/systemd/pto-btop-agent.service").read_text()
    assert str(root / "config/node/agent.json") in unit
    assert str(root / "app/current/bin/pto-btop-agent") in unit
    # An upgrade changes the application pointer but never touches user data.
    readme = package / "README.md"
    readme.write_text(readme.read_text() + "\nPackaging upgrade fixture.\n")
    manifest_path = package / "package.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["files"]["README.md"] = hashlib.sha256(readme.read_bytes()).hexdigest()
    manifest_path.write_text(json.dumps(manifest))
    run(*command)
    upgraded = (root / "app/current").readlink()
    assert upgraded != initial and (root / "app" / initial).is_dir()
    run(sys.executable, str(root / "app" / initial / "install.py"),
        "--root", str(root), "--bin-dir", str(bindir))
    assert (root / "app/current").readlink() == initial
    run(*command)
    assert (root / "app/current").readlink() == upgraded
    for name in ("config", "state", "logs", "tmp"):
        marker = root / name / "preserve-me"
        assert marker.read_bytes() == b"user data\x00\xff"
        assert marker.stat().st_mode & 0o777 == 0o600
    # Wrong CPU architecture / glibc baseline leave the old version usable.
    original_manifest = manifest_path.read_text()
    for field, value in (("architecture", "wrong-architecture"), ("minimum_glibc", "999.0")):
        changed = dict(manifest, **{field: value})
        manifest_path.write_text(json.dumps(changed))
        run(*command, succeeds=False)
        assert (root / "app/current").readlink() == upgraded
    manifest_path.write_text(original_manifest)
    # Corrupt payload is rejected before copying or switching app/current.
    original_readme = readme.read_bytes()
    readme.write_text("corrupt")
    run(*command, succeeds=False)
    assert (root / "app/current").readlink() == upgraded
    readme.write_bytes(original_readme)
    # Do not take over a preexisting, unrelated command.
    (bindir / "pto-btop").unlink()
    (bindir / "pto-btop").write_text("another tool")
    run(*command, succeeds=False)
    assert (bindir / "pto-btop").read_text() == "another tool"
    assert (root / "app/current").readlink() == upgraded
    # Reject a payload directory that redirects verification outside the bundle.
    moved_bin = base / "external-bin"
    shutil.move(str(package / "bin"), moved_bin)
    (package / "bin").symlink_to(moved_bin, target_is_directory=True)
    run(*command, "--check", succeeds=False)
    print("Release install, upgrade, runtime discovery and rejection checks passed")
